import json
import os
import sys
import time
import requests

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
        sys.stderr.reconfigure(encoding="utf-8", line_buffering=True)
    except Exception:
        pass

MANIFEST_PATH = os.path.join("public", "audio", "tts", "manifest.json")
OUTPUT_DIR = os.path.join("public", "audio", "tts")
MODEL_ID = "fish-audio/s2.1-pro-free:free"
API_URL = "https://openrouter.ai/api/v1/audio/speech"

# API key priority: 1) command-line argument, 2) OPENROUTER_API_KEY env var
API_KEY = None
if len(sys.argv) > 1 and sys.argv[1].startswith("sk-"):
    API_KEY = sys.argv[1]
else:
    API_KEY = os.environ.get("OPENROUTER_API_KEY")

if not API_KEY:
    # Fallback to key provided during session
    API_KEY = "REDACTED_API_KEY"

if not os.path.exists(OUTPUT_DIR):
    os.makedirs(OUTPUT_DIR, exist_ok=True)

if not os.path.exists(MANIFEST_PATH):
    print(f"Error: {MANIFEST_PATH} not found.", flush=True)
    sys.exit(1)

with open(MANIFEST_PATH, "r", encoding="utf-8") as f:
    manifest = json.load(f)

print("=" * 65, flush=True)
print("🎙️ OPENROUTER FISH AUDIO S2.1 PRO FREE PREGENERATOR (PYTHON)", flush=True)
print(f"🎙️ Model: {MODEL_ID}", flush=True)
print(f"🎙️ Endpoint: {API_URL}", flush=True)
print(f"🎙️ Total Steps to Process: {len(manifest)}", flush=True)
print("=" * 65 + "\n", flush=True)

headers = {
    "Authorization": f"Bearer {API_KEY}",
    "Content-Type": "application/json",
    "HTTP-Referer": "http://localhost:4321",
    "X-Title": "10301351 Data Science Study Guide"
}

success_count = 0
failed_count = 0

for idx, (file_key, entry) in enumerate(manifest.items(), 1):
    formula_id = entry.get("formulaId")
    step_index = entry.get("stepIndex")
    text = entry.get("text")
    file_name = f"{formula_id}_step_{step_index}.mp3"
    target_path = os.path.join(OUTPUT_DIR, file_name)

    # Check if already generated by fish-audio
    if entry.get("provider") == MODEL_ID and os.path.exists(target_path) and os.path.getsize(target_path) > 1000:
        print(f"[{idx}/{len(manifest)}] ⏭️ Skipped (already Fish Audio): {file_name}", flush=True)
        continue

    print(f"[{idx}/{len(manifest)}] ⏳ Generating Fish Audio for [{formula_id}] Step {step_index}...", flush=True)
    print(f"   Text: \"{text[:45]}...\"", flush=True)

    payload = {
        "model": MODEL_ID,
        "input": text,
        "response_format": "mp3"
    }

    try:
        response = requests.post(API_URL, headers=headers, json=payload, timeout=35)
        
        if response.status_code == 200 and len(response.content) > 1000:
            with open(target_path, "wb") as out_f:
                out_f.write(response.content)

            entry["provider"] = MODEL_ID
            entry["fileSizeBytes"] = len(response.content)
            entry["generatedAt"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            success_count += 1
            print(f"   ✅ Saved: {file_name} ({len(response.content):,} bytes)", flush=True)

            # Save progress incrementally
            with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
                json.dump(manifest, f, ensure_ascii=False, indent=2)
        else:
            failed_count += 1
            print(f"   ❌ HTTP {response.status_code}: {response.text[:200]}", flush=True)

    except Exception as e:
        failed_count += 1
        print(f"   ❌ Exception: {e}", flush=True)

    # Respect OpenRouter rate limit: <= 20 reqs/min -> sleep 3.2s
    time.sleep(3.2)

# Final save
with open(MANIFEST_PATH, "w", encoding="utf-8") as f:
    json.dump(manifest, f, ensure_ascii=False, indent=2)

print("\n" + "=" * 65, flush=True)
print("🏁 COMPLETED FISH AUDIO S2.1 PRO FREE GENERATION!", flush=True)
print(f"📊 Success: {success_count} | Failed: {failed_count}", flush=True)
print(f"📄 Manifest Updated: {MANIFEST_PATH}", flush=True)
print("=" * 65, flush=True)
